export function translate(text:string, language:Language):string {
  if (language==="sv") return text
  const key=text.replace(/\s+/g," ").trim()
  const found=english[key] ?? ({måndag:"Monday",tisdag:"Tuesday",onsdag:"Wednesday",torsdag:"Thursday",fredag:"Friday",lördag:"Saturday",söndag:"Sunday"} as Record<string,string>)[key] ?? recipeTextEn[key] ?? coreContentEn[key]
  if (found) return text.replace(text.trim(),found)
  if (key.startsWith("Målet kräver cirka ")) {
    const pace=key.match(/cirka ([\d,.]+) kg/)?.[1]?.replace(",", ".") ?? "–"
    const weeks=key.match(/minst (\d+) veckor/)?.[1]
    return `This goal requires about ${pace} kg per week. ${key.includes("Takten är för hög") ? "This pace is too high for Livskraft. Adjust your target weight or timeframe before a plan can be created." : "This is an aggressive goal. We recommend a longer timeframe and will not increase restriction or exercise to reach this pace."} ${weeks ? `For a gentler pace, choose ${Number(weeks)>12?`about ${Math.ceil(Number(weeks)*12/52)} months (at least ${weeks} weeks)`:`at least ${weeks} weeks`} or a smaller weight change.` : "Choose a smaller intermediate goal and seek healthcare guidance for a longer-term goal."} Fasting, punishment exercise and extreme calorie restriction are never used. This is planning support, not a medical assessment.`
  }
  if (/^\d+ minuter · /.test(key)) return key.split(" · ").map(part=>translate(part,language)).join(" · ")
  if (/^[\d,. ]+ (steg|minuter)$/.test(key)) return key.replace("steg","steps").replace("minuter","minutes")
  if (key.includes("Du har loggat träning ") || key.includes("Stegen har legat under ditt mål på de ")) return key
    .replace(/Du har loggat träning (\d+) av (\d+) hittills planerade dagar under de senaste två veckorna. Kortare pass kan bli lättare att få plats med./g,"You recorded training on $1 of $2 planned days over the last two weeks. Shorter sessions may fit your routine more easily.")
    .replace(/Stegen har legat under ditt mål på de (\d+) loggade dagarna. Vi föreslår mindre, praktiska rörelsepauser utan att höja målet./g,"Steps were below your goal on the $1 recorded days. We suggest shorter, practical movement breaks without raising the goal.")
  if (key.includes(": promenadförslaget delas upp")) return translate(key.split(":")[0],language)+": the suggested walk is split into two short movement breaks."
  const swap=key.match(/^([^:]+): (.+) \((\d+) min\) byts till (.+) \((\d+) min\).$/)
  if(swap) return `${translate(swap[1],language)}: ${translate(swap[2],language)} (${swap[3]} min) changes to ${translate(swap[4],language)} (${swap[5]} min).`
  if (/^\d+ avklarat pass$/.test(key)) return key.replace("avklarat pass","completed workout")
  if (/^\d+ avklarade pass$/.test(key)) return key.replace("avklarade pass","completed workouts")
  if (key.startsWith("Förändring mellan registrerade mätningar:")) return key.replace("Förändring mellan registrerade mätningar:","Change between recorded measurements:")
  if (key.startsWith("Veckosnittet har minskat")) return key.replace("Veckosnittet har minskat","The weekly average has decreased").replace("Fokusera på veckan, inte en enskild dag.","Focus on the week, not a single day.")
  if (key.endsWith("cm (senast sparat)")) return key.replace("senast sparat","latest saved")
  if (key.startsWith("cirka ") && key.includes("månader")) return key.replace("cirka","about").replace("månader","months").replace("veckor","weeks")
  if (/^\d+ sek$/.test(key)) return key.replace("sek","sec")
  if (/^\d+\/ben$/.test(key)) return key.replace("/ben","/leg")
  return text.replace(/^(\d+) veckor$/, "$1 weeks").replace(/^(\d+) vecka$/, "$1 week").replace(/^(\d+) månader$/, "$1 months")
}
