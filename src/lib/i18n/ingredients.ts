export function ingredientEnglish(text:string):string {
  let result=text
  // Longest matching ingredient name wins; replacements operate on the original text once.
  const words=Object.keys(ingredientTerms).sort((a,b)=>b.length-a.length)
  const pattern=new RegExp(words.map(w=>w.replace(/[.*+?^${}()|[\]\\]/g,"\\$&")).join("|"),"gi")
  result=result.replace(pattern,word=>ingredientTerms[word.toLowerCase()]??word)
  return result.replace(/(\d),(\d)/g,"$1.$2").replace(/\bmsk\b/g,"tbsp").replace(/\btsk\b/g,"tsp").replace(/\bkrm\b/g,"ml").replace(/\bst\s+/g,"").replace(/\bskivor\b/g,"slices").replace(/\bskiva\b/g,"slice").replace(/\bburk(?:ar)?\b/g,"can").replace(/\bportioner\b/g,"servings").replace(/\bportion\b/g,"serving").replace(/mängd enligt förpackningens portionsangivelse/g,"amount per the serving size on the package").replace(/till (\d+) receptportion(?:er)?/g,(_,n)=>`for ${n} recipe serving${n==="1"?"":"s"}`)
}
